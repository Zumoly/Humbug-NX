#!/usr/bin/env python3
"""gen_offsets.py -- source/dcr_offsets.h for Humbug 2.2.4 (Unity 2019.2.15f1).

The addresses were read from the disassembly of that build's libraries. This
script adds each one's first four words as its guard, so a different copy of the
game is refused instead of patched wrongly.

usage: gen_offsets.py <lib/armeabi-v7a folder> <output file>
"""
import struct
import sys

libdir, out = sys.argv[1], sys.argv[2]


def loader(name):
    d = open(libdir + "/" + name, "rb").read()
    ph, pn = struct.unpack_from("<I", d, 28)[0], struct.unpack_from("<H", d, 44)[0]
    segs = []
    for i in range(pn):
        t, off, va, _, fs = struct.unpack_from("<5I", d, ph + i * 32)
        if t == 1:
            segs.append((va, off, fs))

    def guard(rva):
        for va, off, fs in segs:
            if va <= rva < va + fs:
                return struct.unpack_from("<4I", d, rva - va + off)
        raise SystemExit("no segment holds 0x%x" % rva)

    return guard


def hexg(words):
    return "{ " + ", ".join("0x%08xu" % w for w in words) + " }"


unity, il2cpp = loader("libunity.so"), loader("libil2cpp.so")

# Unity's Thumb functions: the frame pacer.
UNITY = {
    "WaitVSync": 0x1f1ccc,
    "ChoreographerEnableVSync": 0x1f1e6c,
    "ChoreographerStopVSync": 0x1f1f20,
}
VSYNC_DATA = {"MUTEX": 0xa38d14, "COND": 0xa38d18, "COUNTER": 0xa38d1c}

# IL2CPP's Boehm collector: GC_suspend_handler, and what it uses.
GC_HANDLER = 0x201a0c
GC_DATA = {
    "STOP_COUNT": 0xba8578,
    "WORLD_STOPPED": 0xba857c,
    "RETRY_SIGNALS": 0xba8580,
    "THREADS": 0xba858c,
    "ACK_SEM": 0xc2a7f0,
    "SIG_SUSPEND": 0xb8abb8,
    "SIG_RESTART": 0xb8abbc,
}

# C# methods, from the IL2CPP metadata.
GAME = {
    "SetRestartEnabled": 0x312924,
    "SetUndoEnabled": 0x312958,
    "RestartClicked": 0x3131b8,
    "UndoClicked": 0x312c34,
    "MainMenuClicked": 0x3131e0,
    "SetInteractable": 0x274984,
    "GetGameObject": 0x269ef0,
    "ActiveInHierarchy": 0x268e04,
}

w = ["/* GENERATED by tools/gen_offsets.py -- do not hand-edit.",
     " * Humbug 2.2.4, Unity 2019.2.15f1, armeabi-v7a. */",
     "#ifndef DCR_OFFSETS_H", "#define DCR_OFFSETS_H", "#include <stdint.h>", "",
     "typedef struct { const char *name; uint32_t rva; uint32_t guard[4]; } DcrSite;", ""]
for n, a in UNITY.items():
    w.append("#define DCR_RVA_%s 0x%07xu" % (n, a))
    w.append("static const uint32_t DCR_GUARD_%s[4] = %s;" % (n, hexg(unity(a))))
for n, a in VSYNC_DATA.items():
    w.append("#define DCR_VSYNC_%s 0x%07xu" % (n, a))
w.append("")
w.append("#define HB_RVA_GC_HANDLER 0x%07xu" % GC_HANDLER)
w.append("static const uint32_t HB_GUARD_GC_HANDLER[4] = %s;" % hexg(il2cpp(GC_HANDLER)))
for n, a in GC_DATA.items():
    w.append("#define HB_RVA_GC_%s 0x%07xu" % (n, a))
w.append("")
for n, a in GAME.items():
    w.append('static const DcrSite HB_SITE_%s = { "%s", 0x%07xu, %s };' % (n, n, a, hexg(il2cpp(a))))
w += ["", "#endif /* DCR_OFFSETS_H */", ""]
open(out, "w", newline="\n").write("\n".join(w))
